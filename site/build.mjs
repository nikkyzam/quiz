// Builds the Study Hall site.
//
//   node site/build.mjs
//
// Source lives in site/ (banks/*.json, site.json, the two templates, style.css,
// engine.js). Every page it writes is generated — edit site/, then rebuild, rather
// than editing the HTML in 6/ or the root by hand.
//
//   /                  index.html          pick a grade
//   /6/                6/index.html        pick a subject
//   /6/math/ /6/ss/ /6/ela/                the tests for that subject
//   old page names                         redirect stubs (see "redirects" in site.json)

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const read = (...p) => fs.readFileSync(path.join(here, ...p), 'utf8');
const write = (rel, text) => {
  const file = path.join(root, rel);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
  return rel;
};

const site = JSON.parse(read('site.json'));
const style = read('style.css').trimEnd();
const engine = read('engine.js').trimEnd();
const subjectTpl = read('subject.html');
const cardsTpl = read('cards.html');

const GENERATED = '<!-- Generated by site/build.mjs — edit the files in site/, not this page. -->\n';
// the doctype must stay first, or older browsers fall into quirks mode
const stamp = html => html.replace(/^<!doctype html>\n/i, m => m + GENERATED);

/* ---------- banks ---------- */

const banks = {};
for (const f of fs.readdirSync(path.join(here, 'banks'))) {
  if (f.endsWith('.json')) banks[f.replace(/\.json$/, '')] = JSON.parse(read('banks', f));
}

const isForms = bank => !Array.isArray(bank);
const allQuestions = bank => (isForms(bank) ? Object.values(bank).flat() : bank);

function validate() {
  const problems = [];
  for (const [id, bank] of Object.entries(banks)) {
    for (const q of allQuestions(bank)) {
      const at = `${id} Q${q.n}`;
      const bad = msg => problems.push(`${at}: ${msg}`);
      if (!q.why) bad('missing "why"');
      switch (q.type) {
        case 'mc':
          if (!Number.isInteger(q.answer) || q.answer < 0 || q.answer >= (q.choices || []).length) bad('answer index out of range');
          break;
        case 'tf':
          if (q.answer !== 0 && q.answer !== 1) bad('true/false answer must be 0 or 1');
          break;
        case 'multi':
          if (!Array.isArray(q.answer) || !q.answer.length || q.answer.some(a => a < 0 || a >= q.choices.length)) bad('bad select-all answer');
          break;
        case 'match': {
          const rights = (q.pairs || []).map(p => p[1]);
          if (!q.pairs || q.pairs.length < 2) bad('matching needs at least 2 pairs');
          if (new Set(rights).size !== rights.length) bad('duplicate match options — the dropdown could not tell them apart');
          break;
        }
        case 'order':
          if (!q.items || q.items.length < 2) bad('ordering needs at least 2 items');
          else if (new Set(q.items).size !== q.items.length) bad('duplicate ordering items');
          break;
        case 'text':
          if (!q.hint) bad('write-in needs a hint');
          if (q.grade === 'number') { if (typeof q.answer !== 'number') bad('numeric answer must be a number'); }
          else if (!q.accept?.length || !q.display) bad('write-in needs "accept" and "display"');
          break;
        default:
          bad(`unknown type "${q.type}"`);
      }
    }
    // numbering should run 1..n in every plain bank (the math forms keep the study guide's own labels)
    if (!isForms(bank)) bank.forEach((q, i) => { if (q.n !== String(i + 1)) problems.push(`${id}: numbering gap at index ${i} (found "${q.n}")`); });
  }
  if (problems.length) {
    console.error('Question banks are invalid:\n  ' + problems.join('\n  '));
    process.exit(1);
  }
}
validate();

/* ---------- helpers ---------- */

const fill = (tpl, vars) => {
  // function replacers, so "$8" or "$&" inside the content is never read as a replacement pattern
  let out = tpl;
  for (const [k, v] of Object.entries(vars)) out = out.replace(`__${k}__`, () => v);
  const left = out.match(/__[A-Z]+__/);
  if (left) throw new Error('unfilled placeholder ' + left[0]);
  return out;
};

const chips = list => list.map(t => `<span class="flag-chip">${t}</span>`).join('\n      ');

// The question count a student actually faces: forms are alternatives, so a test with forms is
// "up to" its longest non-standalone form plus the add-on set, if it has one.
const testDef = id => site.grades.flatMap(g => g.subjects).flatMap(s => s.tests || []).find(t => t.id === id);
const questionCount = testIds => testIds.reduce((n, id) => {
  const b = banks[id];
  if (!isForms(b)) return n + b.length;
  const t = testDef(id);
  const longestBase = Math.max(...t.forms.filter(f => !f.standalone).map(f => b[f.bank].length));
  return n + longestBase + (t.addOn ? b[t.addOn.set].length : 0);
}, 0);
const formCount = testIds => testIds.reduce((n, id) => n + (isForms(banks[id]) ? testDef(id).forms.length : 0), 0);
const hasForms = testIds => testIds.some(id => isForms(banks[id]));
const typeCount = testIds => new Set(testIds.flatMap(id => allQuestions(banks[id]).map(q => q.type))).size;
const plural = (n, w) => `${n} ${w}${n === 1 ? '' : 's'}`;

const testIdsOf = subject => (subject.tests || []).map(t => t.id);

function subjectMeta(subject) {
  const ids = testIdsOf(subject);
  if (hasForms(ids)) return `${formCount(ids)} forms · up to ${questionCount(ids)} questions`;
  return `${plural(ids.length, 'test')} · ${plural(questionCount(ids), 'question')}`;
}

const crumbs = trail => {
  const parts = trail.map((c, i) => (i === trail.length - 1
    ? `<span aria-current="page">${c.name}</span>`
    : `<a href="${c.href}">${c.name}</a>`));
  return `<nav class="crumbs" aria-label="Breadcrumb">${parts.join('<span class="sep">›</span>')}</nav>`;
};

const card = ({ href, label, name, desc, meta, soon }) => {
  const inner = `<span class="tc-label">${label}</span>`
    + `<span class="tc-name">${name}</span>`
    + `<span class="tc-desc">${desc}</span>`
    + `<span class="tc-meta">${meta}</span>`;
  return soon
    ? `      <div class="test-card soon" aria-disabled="true">${inner}</div>`
    : `      <a class="test-card" href="${href}">${inner}</a>`;
};

const written = [];

/* ---------- subject pages: /6/math/, /6/ss/, /6/ela/ ---------- */

for (const grade of site.grades) {
  for (const subject of grade.subjects) {
    if (subject.soon || subject.href) continue;
    const ids = testIdsOf(subject);
    const forms = hasForms(ids);

    const siblings = grade.subjects
      .filter(s => s.id !== subject.id)
      .map(s => (s.soon ? null : `<a href="${s.href ? '../' + s.href : '../' + s.id + '/'}">${s.name}</a>`))
      .filter(Boolean);

    const data = {
      banks: Object.fromEntries(ids.map(id => [id, banks[id]])),
      config: {
        storagePrefix: subject.prefix,
        tests: subject.tests.map(({ id, label, name, desc, forms, addOn, lede }) => ({ id, label, name, desc, forms, addOn, lede }))
      }
    };

    const page = fill(subjectTpl, {
      TITLE: `${grade.name} ${subject.name}`,
      STYLE: style,
      CRUMBS: crumbs([
        { name: site.home.title, href: '../../' },
        { name: grade.name, href: '../' },
        { name: subject.name }
      ]),
      EYEBROW: `${grade.name} · ${subject.name}`,
      H1: subject.name,
      SUB: `${subject.blurb} Nothing is graded until you submit — then every miss explains itself.`,
      CHIPS: chips([
        ...(forms ? [`${formCount(ids)} forms`] : ids.length > 1 ? [plural(ids.length, 'test')] : []),
        `${forms ? 'up to ' : ''}${plural(questionCount(ids), 'question')}`,
        plural(typeCount(ids), 'question type')
      ]),
      FOOTER: (siblings.length ? `${grade.name}: ${siblings.join(' · ')}<br>` : '')
        + `<a href="../">All ${grade.name} subjects</a> · <a href="../../">All grades</a>`,
      // "<" escaped so question text can never close the script element early
      DATA: JSON.stringify(data).replace(/</g, '\\u003c'),
      ENGINE: engine
    });
    written.push(write(`${grade.id}/${subject.id}/index.html`, stamp(page)));
  }
}

/* ---------- grade pages: /6/, /5/ ---------- */

for (const grade of site.grades) {
  const cards = grade.subjects.map(s => card({
    href: s.href || `${s.id}/`,
    label: 'Subject',
    name: s.name,
    desc: s.blurb,
    meta: s.soon ? 'Coming soon' : s.href ? 'Opens the quiz' : subjectMeta(s),
    soon: !!s.soon
  })).join('\n');

  const live = grade.subjects.filter(s => !s.soon && !s.href);
  const page = fill(cardsTpl, {
    TITLE: `${grade.name} — ${site.home.title}`,
    STYLE: style,
    CRUMBS: crumbs([{ name: site.home.title, href: '../' }, { name: grade.name }]),
    EYEBROW: grade.name,
    H1: grade.name,
    SUB: grade.blurb,
    CHIPS: chips([
      plural(grade.subjects.filter(s => !s.soon).length, 'subject'),
      ...(live.length ? [plural(live.reduce((n, s) => n + testIdsOf(s).length, 0), 'test')] : [])
    ]),
    HEADING: 'Choose a subject',
    CARDS: cards,
    FOOTER: `<a href="../">All grades</a>`
  });
  written.push(write(`${grade.id}/index.html`, stamp(page)));
}

/* ---------- home: / ---------- */

{
  const cards = site.grades.map(g => {
    const live = g.subjects.filter(s => !s.soon);
    return card({
      href: `${g.id}/`,
      label: 'Grade',
      name: g.name,
      desc: live.map(s => s.name).join(' · '),
      meta: plural(live.length, 'subject')
    });
  }).join('\n');

  const page = fill(cardsTpl, {
    TITLE: site.home.title,
    STYLE: style,
    CRUMBS: '',
    EYEBROW: site.home.eyebrow,
    H1: site.home.h1,
    SUB: site.home.sub,
    CHIPS: chips([plural(site.grades.length, 'grade')]),
    HEADING: 'Choose your grade',
    CARDS: cards,
    FOOTER: 'Study Hall'
  });
  written.push(write('index.html', stamp(page)));
}

/* ---------- redirects from the old page names ---------- */

for (const [from, to] of Object.entries(site.redirects || {})) {
  const stub = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta http-equiv="refresh" content="0; url=${to}">
<link rel="canonical" href="${to}">
<title>Moved to Study Hall</title>
<style>
  body{margin:0;min-height:100vh;display:flex;align-items:center;justify-content:center;
       background:#f3ede0;color:#2a2620;font-family:Georgia,serif;padding:24px;text-align:center}
  @media (prefers-color-scheme:dark){body{background:#141b2c;color:#ece4d2}}
  a{color:inherit}
</style>
</head>
<body>
  <p>This test has moved.<br><a href="${to}">Continue to Study Hall →</a></p>
  <script>location.replace('${to}');</script>
</body>
</html>
`;
  written.push(write(from, stamp(stub)));
}

/* ---------- report ---------- */

const total = Object.values(banks).reduce((n, b) => n + allQuestions(b).length, 0);
console.log(`Built ${written.length} pages from ${Object.keys(banks).length} banks (${total} questions):`);
for (const w of written) {
  console.log('  ' + w.padEnd(34) + (fs.statSync(path.join(root, w)).size / 1024).toFixed(0).padStart(4) + ' KB');
}
